import ExcelJS from "exceljs";
import type { DataPoint } from "../rag/types";

export async function buildXlsx(
  filename: string,
  dataPoints: DataPoint[],
): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "ContractCounsel";
  wb.created = new Date();

  const ws = wb.addWorksheet("Data Points", {
    views: [{ state: "frozen", ySplit: 1 }],
  });

  ws.columns = [
    { header: "Field", key: "field", width: 32 },
    { header: "Value", key: "value", width: 48 },
    { header: "Quote", key: "quote", width: 60 },
    { header: "Page", key: "page", width: 8 },
    { header: "Verified", key: "verified", width: 10 },
  ];

  const header = ws.getRow(1);
  header.font = { bold: true, color: { argb: "FFFFFFFF" } };
  header.fill = {
    type: "pattern",
    pattern: "solid",
    fgColor: { argb: "FF08070A" },
  };
  header.alignment = { vertical: "middle", horizontal: "left" };
  header.height = 22;

  for (const dp of dataPoints) {
    const row = ws.addRow({
      field: dp.field,
      value: dp.value,
      quote: dp.quote,
      page: dp.page,
      verified: dp.verified ? "yes" : "no",
    });
    row.alignment = { vertical: "top", wrapText: true };
  }

  ws.getColumn("field").font = { bold: true };
  ws.getColumn("quote").font = { italic: true };

  const titleRowNumber = ws.rowCount + 2;
  ws.getCell(`A${titleRowNumber}`).value = `Source: ${filename}`;
  ws.getCell(`A${titleRowNumber}`).font = { italic: true, color: { argb: "FF807A70" } };
  ws.getCell(`A${titleRowNumber + 1}`).value =
    "Generated by ContractCounsel. Document analysis, not legal advice.";
  ws.getCell(`A${titleRowNumber + 1}`).font = {
    italic: true,
    color: { argb: "FF807A70" },
  };

  const buf = await wb.xlsx.writeBuffer();
  return Buffer.from(buf);
}
